/**
 * `abra setup launcher` — POSIX sh wrapper that exec's the agent's node +
 * this package's dist/index.js (fixes mise "abra is not a valid shim" and
 * peer exe_mismatch from `#!/usr/bin/env node`).
 *
 * `abra setup polkit` — install the shipped PolKit policy via install-polkit.sh.
 *
 * The launcher does NOT strip NODE_OPTIONS: the agent already rejects dangerous
 * inject/debug flags. Keep the environment as-is.
 */
import { execFileSync, type ExecFileSyncOptions } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import type { Command } from "commander";

const require = createRequire(import.meta.url);
const { version: PKG_VERSION } = require("../../package.json") as { version: string };

const GENERATED_MARKER_PREFIX = "# generated by abra setup launcher v";

export type SetupLog = (msg: string) => void;

export type SetupLauncherDeps = {
  platform?: NodeJS.Platform;
  homedir?: () => string;
  execPath?: string;
  /** Absolute path to this package's dist/index.js. */
  entryPath?: string;
  version?: string;
  existsSync?: (p: string) => boolean;
  readFileSync?: (p: string, enc: "utf8") => string;
  writeFileSync?: typeof fs.writeFileSync;
  renameSync?: typeof fs.renameSync;
  chmodSync?: typeof fs.chmodSync;
  mkdirSync?: typeof fs.mkdirSync;
  realpathSync?: (p: string) => string;
  /** Resolve `command -v abra` (tests inject). */
  whichAbra?: (pathEnv: string) => string | null;
  pathEnv?: string;
  log?: SetupLog;
  error?: SetupLog;
};

export type SetupPolkitDeps = {
  platform?: NodeJS.Platform;
  /** Absolute path to packaging/linux/dev.abracadabra.policy. */
  policySrc?: string;
  policyDest?: string;
  installScript?: string;
  existsSync?: (p: string) => boolean;
  readFileSync?: (p: string, enc: "utf8") => string;
  /** Run install (tests inject). */
  runInstall?: (cmd: string, args: string[]) => void;
  which?: (bin: string) => string | null;
  log?: SetupLog;
  error?: SetupLog;
};

/** Shell-escape a path for use inside single quotes. */
export function shellSingleQuote(absPath: string): string {
  return `'${absPath.replace(/'/g, `'\\''`)}'`;
}

export function buildLauncherScript(opts: {
  nodePath: string;
  entryPath: string;
  version: string;
}): string {
  const node = shellSingleQuote(opts.nodePath);
  const entry = shellSingleQuote(opts.entryPath);
  return (
    `#!/bin/sh\n` +
    `${GENERATED_MARKER_PREFIX}${opts.version}\n` +
    `# Pins node + dist/index.js so abra-agent peer checks pass (same realpaths).\n` +
    `# Does not strip NODE_OPTIONS — the agent rejects dangerous inject/debug flags.\n` +
    `exec ${node} ${entry} "$@"\n`
  );
}

export function isGeneratedLauncher(content: string): boolean {
  return content.split(/\r?\n/).some((l) => l.startsWith(GENERATED_MARKER_PREFIX));
}

function defaultRealpath(p: string): string {
  return fs.realpathSync(p);
}

function defaultWhichAbra(pathEnv: string): string | null {
  const parts = pathEnv.split(path.delimiter).filter(Boolean);
  for (const dir of parts) {
    const candidate = path.join(dir, "abra");
    try {
      fs.accessSync(candidate, fs.constants.X_OK);
      return candidate;
    } catch {
      /* try next */
    }
  }
  return null;
}

/** Resolve dist/index.js next to this package (works from src/ and dist/). */
export function resolveCliEntrypointFromHere(
  fromUrl: string = import.meta.url,
  existsSync: (p: string) => boolean = (p) => fs.existsSync(p),
): string {
  const here = path.dirname(fileURLToPath(fromUrl));
  // dist/commands → ../index.js; src/commands → ../../dist/index.js
  const asDist = path.resolve(here, "..", "index.js");
  if (existsSync(asDist)) return asDist;
  return path.resolve(here, "..", "..", "dist", "index.js");
}

export type LauncherCheckStatus =
  | "missing"
  | "identical"
  | "outdated_generated"
  | "foreign"
  | "unsupported";

export function classifyLauncherFile(
  existing: string | null,
  expected: string,
): LauncherCheckStatus {
  if (existing === null) return "missing";
  if (existing === expected) return "identical";
  if (isGeneratedLauncher(existing)) return "outdated_generated";
  return "foreign";
}

export function cmdSetupLauncher(
  opts: { dir?: string; force?: boolean; check?: boolean } = {},
  deps: SetupLauncherDeps = {},
): void {
  const log = deps.log ?? ((m) => console.log(m));
  const error = deps.error ?? ((m) => console.error(m));
  const platform = deps.platform ?? process.platform;

  if (platform === "win32") {
    log("abra setup launcher: not needed / unsupported on Windows (exit 0)");
    return;
  }

  const homedir = deps.homedir ?? (() => os.homedir());
  const dir = path.resolve(
    opts.dir?.trim() || path.join(homedir(), ".local", "bin"),
  );
  const target = path.join(dir, "abra");
  const realpath = deps.realpathSync ?? defaultRealpath;
  const existsSync = deps.existsSync ?? ((p) => fs.existsSync(p));
  const readFileSync =
    deps.readFileSync ?? ((p, enc) => fs.readFileSync(p, enc));

  let nodePath: string;
  let entryPath: string;
  try {
    nodePath = realpath(deps.execPath ?? process.execPath);
    entryPath = realpath(deps.entryPath ?? resolveCliEntrypointFromHere());
  } catch (e) {
    error(
      `abra setup launcher: cannot realpath node/entry: ${e instanceof Error ? e.message : String(e)}`,
    );
    process.exitCode = 1;
    return;
  }

  const expected = buildLauncherScript({
    nodePath,
    entryPath,
    version: deps.version ?? PKG_VERSION,
  });

  let existing: string | null = null;
  if (existsSync(target)) {
    try {
      existing = readFileSync(target, "utf8");
    } catch {
      existing = null;
    }
  }

  const status = classifyLauncherFile(existing, expected);

  if (opts.check) {
    switch (status) {
      case "missing":
        log(`check: missing ${target}`);
        log(`  fix: abra setup launcher --dir ${dir}`);
        break;
      case "identical":
        log(`check: ok ${target} (matches current node + entry)`);
        break;
      case "outdated_generated":
        log(`check: outdated generated launcher at ${target}`);
        log(`  fix: abra setup launcher --dir ${dir}`);
        break;
      case "foreign":
        log(`check: foreign file at ${target} (not generated by abra setup launcher)`);
        log(`  fix: abra setup launcher --dir ${dir} --force`);
        break;
    }
    return;
  }

  if (status === "identical") {
    log(`ok: ${target} already up to date`);
    warnPathOrder(dir, target, entryPath, deps, log);
    return;
  }

  if (status === "foreign" && !opts.force) {
    error(
      `refuse: ${target} exists and was not generated by abra setup launcher (use --force to overwrite)`,
    );
    process.exitCode = 1;
    return;
  }

  const mkdirSync = deps.mkdirSync ?? ((p, o) => fs.mkdirSync(p, o));
  const writeFileSync = deps.writeFileSync ?? fs.writeFileSync;
  const renameSync = deps.renameSync ?? fs.renameSync;
  const chmodSync = deps.chmodSync ?? fs.chmodSync;

  try {
    mkdirSync(dir, { recursive: true });
    const tmp = path.join(dir, `.abra-launcher.${process.pid}.tmp`);
    writeFileSync(tmp, expected, { encoding: "utf8", mode: 0o755 });
    chmodSync(tmp, 0o755);
    renameSync(tmp, target);
  } catch (e) {
    error(
      `abra setup launcher: write failed: ${e instanceof Error ? e.message : String(e)}`,
    );
    process.exitCode = 1;
    return;
  }

  log(`ok: wrote ${target}`);
  log(`  node  ${nodePath}`);
  log(`  entry ${entryPath}`);
  warnPathOrder(dir, target, entryPath, deps, log);
}

function warnPathOrder(
  dir: string,
  target: string,
  entryReal: string,
  deps: SetupLauncherDeps,
  log: SetupLog,
): void {
  const pathEnv = deps.pathEnv ?? process.env.PATH ?? "";
  const parts = pathEnv.split(path.delimiter).filter(Boolean);
  const dirOnPath = parts.some((p) => {
    try {
      return path.resolve(p) === path.resolve(dir);
    } catch {
      return p === dir;
    }
  });
  if (!dirOnPath) {
    log(`warn: ${dir} is not on PATH — add it, e.g. export PATH="${dir}:$PATH"`);
  }

  const which = deps.whichAbra ?? defaultWhichAbra;
  const resolved = which(pathEnv);
  if (!resolved) {
    if (dirOnPath) log("warn: command -v abra found nothing — open a new shell or run: hash -r");
    return;
  }

  const realpath = deps.realpathSync ?? defaultRealpath;
  let resolvedReal: string;
  try {
    resolvedReal = realpath(resolved);
  } catch {
    resolvedReal = resolved;
  }

  const targetReal = (() => {
    try {
      return realpath(target);
    } catch {
      return target;
    }
  })();

  if (path.resolve(resolved) === path.resolve(target) || resolvedReal === targetReal) {
    return;
  }

  // npm bin symlink → same entry is OK (peer check allows it), but mise/npm
  // ahead of the launcher still causes "not a valid shim" or wrong node.
  let entryMatch = false;
  try {
    entryMatch = resolvedReal === entryReal;
  } catch {
    entryMatch = false;
  }

  if (entryMatch) {
    log(
      `warn: command -v abra → ${resolved} (npm bin; same entry). Prefer the launcher earlier on PATH to pin the agent node: export PATH="${dir}:$PATH" && hash -r`,
    );
    return;
  }

  log(
    `warn: command -v abra → ${resolved} (shadows ${target}). Fix: put ${dir} first on PATH, or remove/rename the other abra (e.g. mise shim), then: hash -r`,
  );
}

function defaultWhich(bin: string): string | null {
  const pathEnv = process.env.PATH ?? "";
  for (const dir of pathEnv.split(path.delimiter).filter(Boolean)) {
    const c = path.join(dir, bin);
    try {
      fs.accessSync(c, fs.constants.X_OK);
      return c;
    } catch {
      /* next */
    }
  }
  return null;
}

function defaultPolicySrc(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const candidates = [
    path.resolve(here, "..", "..", "packaging", "linux", "dev.abracadabra.policy"),
    path.resolve(here, "..", "packaging", "linux", "dev.abracadabra.policy"),
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return c;
  }
  return candidates[0];
}

function defaultInstallScript(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const candidates = [
    path.resolve(here, "..", "..", "scripts", "install-polkit.sh"),
    path.resolve(here, "..", "scripts", "install-polkit.sh"),
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return c;
  }
  return candidates[0];
}

export const POLKIT_DEST =
  "/usr/share/polkit-1/actions/dev.abracadabra.policy";

export function cmdSetupPolkit(
  opts: { check?: boolean } = {},
  deps: SetupPolkitDeps = {},
): void {
  const log = deps.log ?? ((m) => console.log(m));
  const error = deps.error ?? ((m) => console.error(m));
  const platform = deps.platform ?? process.platform;

  if (platform !== "linux") {
    log(`abra setup polkit: no-op on ${platform} (Linux only)`);
    return;
  }

  const existsSync = deps.existsSync ?? ((p) => fs.existsSync(p));
  const readFileSync =
    deps.readFileSync ?? ((p, enc) => fs.readFileSync(p, enc));
  const src = deps.policySrc ?? defaultPolicySrc();
  const dest = deps.policyDest ?? POLKIT_DEST;

  if (!existsSync(src)) {
    error(`abra setup polkit: policy not found at ${src}`);
    process.exitCode = 1;
    return;
  }

  let srcBody: string;
  try {
    srcBody = readFileSync(src, "utf8");
  } catch (e) {
    error(`abra setup polkit: cannot read ${src}: ${e instanceof Error ? e.message : String(e)}`);
    process.exitCode = 1;
    return;
  }

  let destBody: string | null = null;
  if (existsSync(dest)) {
    try {
      destBody = readFileSync(dest, "utf8");
    } catch {
      destBody = null;
    }
  }

  if (opts.check) {
    if (destBody === null) {
      log(`check: missing ${dest}`);
      log("  fix: abra setup polkit");
    } else if (destBody === srcBody) {
      log(`check: ok ${dest} (identical)`);
    } else {
      log(`check: outdated ${dest}`);
      log("  fix: abra setup polkit");
    }
    return;
  }

  if (destBody === srcBody) {
    log(`ok: ${dest} already up to date (identical)`);
    return;
  }

  const installScript = deps.installScript ?? defaultInstallScript();
  if (!existsSync(installScript)) {
    error(`abra setup polkit: install script not found at ${installScript}`);
    process.exitCode = 1;
    return;
  }

  const which = deps.which ?? defaultWhich;
  const sudo = which("sudo");
  const pkexec = which("pkexec");
  let cmd: string;
  let args: string[];
  if (sudo) {
    cmd = sudo;
    args = [installScript];
  } else if (pkexec) {
    cmd = pkexec;
    args = [installScript];
  } else {
    error("abra setup polkit: neither sudo nor pkexec found on PATH");
    process.exitCode = 1;
    return;
  }

  const printable = `${cmd} ${args.map(shellSingleQuote).join(" ")}`;
  log(`running: ${printable}`);

  const run =
    deps.runInstall ??
    ((c, a) => {
      execFileSync(c, a, { stdio: "inherit" } satisfies ExecFileSyncOptions);
    });

  try {
    run(cmd, args);
  } catch (e) {
    error(
      `abra setup polkit: install failed: ${e instanceof Error ? e.message : String(e)}`,
    );
    process.exitCode = 1;
  }
}

/**
 * Best-effort launcher install (never throws / never sets exitCode).
 * For future agent-unit install hooks — none exist today.
 */
export function trySetupLauncherBestEffort(deps: SetupLauncherDeps = {}): void {
  try {
    const prev = process.exitCode;
    cmdSetupLauncher({}, { ...deps, log: deps.log ?? (() => {}), error: deps.error ?? (() => {}) });
    process.exitCode = prev;
  } catch {
    /* ignore */
  }
}

export function registerSetupCommands(program: Command): void {
  const setup = program.command("setup").description("Install local helpers (launcher, polkit policy)");

  setup
    .command("launcher")
    .description(
      "Write ~/.local/bin/abra that exec's this node + dist/index.js (fixes mise shims / peer exe_mismatch)",
    )
    .option("--dir <path>", "install directory", undefined)
    .option("--force", "overwrite a non-generated file")
    .option("--check", "report status only")
    .action(async (opts: { dir?: string; force?: boolean; check?: boolean }) => {
      cmdSetupLauncher({
        dir: opts.dir,
        force: Boolean(opts.force),
        check: Boolean(opts.check),
      });
    });

  setup
    .command("polkit")
    .description("Install packaging/linux/dev.abracadabra.policy system-wide (Linux)")
    .option("--check", "report installed/missing/outdated without sudo")
    .action(async (opts: { check?: boolean }) => {
      cmdSetupPolkit({ check: Boolean(opts.check) });
    });
}
