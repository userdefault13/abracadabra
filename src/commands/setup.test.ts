import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, it, expect, afterEach } from "vitest";
import {
  buildLauncherScript,
  classifyLauncherFile,
  cmdSetupLauncher,
  cmdSetupPolkit,
  isGeneratedLauncher,
  shellSingleQuote,
} from "./setup.js";

describe("shellSingleQuote / buildLauncherScript", () => {
  it("escapes single quotes for POSIX sh", () => {
    expect(shellSingleQuote("/opt/o's/node")).toBe(`'/opt/o'\\''s/node'`);
  });

  it("builds an exec launcher without node flags", () => {
    const body = buildLauncherScript({
      nodePath: "/usr/bin/node",
      entryPath: "/opt/abra/dist/index.js",
      version: "1.0.6",
    });
    expect(body.startsWith("#!/bin/sh\n")).toBe(true);
    expect(isGeneratedLauncher(body)).toBe(true);
    expect(body).toContain("generated by abra setup launcher v1.0.6");
    expect(body).toContain(`exec '/usr/bin/node' '/opt/abra/dist/index.js' "$@"`);
    expect(body).not.toContain("--require");
    expect(body).toContain("Does not strip NODE_OPTIONS");
  });

  it("classify: identical / outdated / foreign / missing", () => {
    const expected = buildLauncherScript({
      nodePath: "/n",
      entryPath: "/e",
      version: "1",
    });
    expect(classifyLauncherFile(null, expected)).toBe("missing");
    expect(classifyLauncherFile(expected, expected)).toBe("identical");
    expect(
      classifyLauncherFile(
        buildLauncherScript({ nodePath: "/other", entryPath: "/e", version: "1" }),
        expected,
      ),
    ).toBe("outdated_generated");
    expect(classifyLauncherFile("#!/bin/sh\necho hi\n", expected)).toBe("foreign");
  });
});

describe("cmdSetupLauncher", () => {
  const tmps: string[] = [];
  afterEach(() => {
    for (const t of tmps) fs.rmSync(t, { recursive: true, force: true });
    tmps.length = 0;
    process.exitCode = undefined;
  });

  it("win32 is a no-op exit 0", () => {
    const logs: string[] = [];
    cmdSetupLauncher({}, { platform: "win32", log: (m) => logs.push(m) });
    expect(logs[0]).toMatch(/not needed \/ unsupported/);
    expect(process.exitCode).toBeUndefined();
  });

  it("writes atomically and is idempotent", () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "abra-launcher-"));
    tmps.push(dir);
    const logs: string[] = [];
    const node = "/mock/node";
    const entry = "/mock/dist/index.js";
    const deps = {
      platform: "linux" as const,
      execPath: node,
      entryPath: entry,
      version: "9.9.9",
      realpathSync: (p: string) => p,
      whichAbra: () => path.join(dir, "abra"),
      pathEnv: dir,
      log: (m: string) => logs.push(m),
      error: (m: string) => logs.push("ERR:" + m),
    };
    cmdSetupLauncher({ dir }, deps);
    const target = path.join(dir, "abra");
    expect(fs.existsSync(target)).toBe(true);
    const mode = fs.statSync(target).mode & 0o777;
    expect(mode).toBe(0o755);
    const body = fs.readFileSync(target, "utf8");
    expect(body).toContain("v9.9.9");
    expect(body).toContain(`exec '${node}' '${entry}' "$@"\n`);

    logs.length = 0;
    cmdSetupLauncher({ dir }, deps);
    expect(logs.some((l) => l.includes("already up to date"))).toBe(true);
  });

  it("refuses foreign file without --force; --check reports", () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "abra-launcher-"));
    tmps.push(dir);
    const target = path.join(dir, "abra");
    fs.writeFileSync(target, "#!/bin/sh\necho foreign\n", { mode: 0o755 });
    const logs: string[] = [];
    const errs: string[] = [];
    const deps = {
      platform: "linux" as const,
      execPath: "/n",
      entryPath: "/e",
      version: "1",
      realpathSync: (p: string) => p,
      whichAbra: () => null,
      pathEnv: "",
      log: (m: string) => logs.push(m),
      error: (m: string) => errs.push(m),
    };
    cmdSetupLauncher({ dir }, deps);
    expect(process.exitCode).toBe(1);
    expect(errs.join("\n")).toMatch(/refuse:.*--force/);

    process.exitCode = undefined;
    logs.length = 0;
    cmdSetupLauncher({ dir, check: true }, deps);
    expect(logs.some((l) => l.includes("foreign"))).toBe(true);

    cmdSetupLauncher({ dir, force: true }, deps);
    expect(isGeneratedLauncher(fs.readFileSync(target, "utf8"))).toBe(true);
  });
});

describe("cmdSetupPolkit", () => {
  it("no-op on non-linux", () => {
    const logs: string[] = [];
    cmdSetupPolkit({}, { platform: "darwin", log: (m) => logs.push(m) });
    expect(logs[0]).toMatch(/no-op/);
  });

  it("--check reports missing / identical / outdated without running install", () => {
    const src = "policy-v1\n";
    const calls: string[] = [];
    const logs: string[] = [];
    cmdSetupPolkit(
      { check: true },
      {
        platform: "linux",
        policySrc: "/src/policy",
        policyDest: "/dest/policy",
        existsSync: (p) => p === "/src/policy",
        readFileSync: () => src,
        runInstall: (c, a) => {
          calls.push(`${c} ${a.join(" ")}`);
        },
        log: (m) => logs.push(m),
      },
    );
    expect(logs.some((l) => l.includes("missing"))).toBe(true);
    expect(calls).toEqual([]);

    logs.length = 0;
    cmdSetupPolkit(
      { check: true },
      {
        platform: "linux",
        policySrc: "/src/policy",
        policyDest: "/dest/policy",
        existsSync: () => true,
        readFileSync: () => src,
        runInstall: (c, a) => {
          calls.push(`${c} ${a.join(" ")}`);
        },
        log: (m) => logs.push(m),
      },
    );
    expect(logs.some((l) => l.includes("identical"))).toBe(true);

    logs.length = 0;
    cmdSetupPolkit(
      { check: true },
      {
        platform: "linux",
        policySrc: "/src/policy",
        policyDest: "/dest/policy",
        existsSync: () => true,
        readFileSync: (p) => (p === "/src/policy" ? src : "old\n"),
        runInstall: (c, a) => {
          calls.push(`${c} ${a.join(" ")}`);
        },
        log: (m) => logs.push(m),
      },
    );
    expect(logs.some((l) => l.includes("outdated"))).toBe(true);
    expect(calls).toEqual([]);
  });

  it("skips install when identical; otherwise runs sudo script", () => {
    const src = "policy-v1\n";
    const calls: string[] = [];
    const logs: string[] = [];
    cmdSetupPolkit(
      {},
      {
        platform: "linux",
        policySrc: "/src/policy",
        policyDest: "/dest/policy",
        installScript: "/scripts/install-polkit.sh",
        existsSync: () => true,
        readFileSync: () => src,
        which: (b) => (b === "sudo" ? "/usr/bin/sudo" : null),
        runInstall: (c, a) => {
          calls.push(`${c} ${a.join(" ")}`);
        },
        log: (m) => logs.push(m),
      },
    );
    expect(calls).toEqual([]);
    expect(logs.some((l) => l.includes("already up to date"))).toBe(true);

    cmdSetupPolkit(
      {},
      {
        platform: "linux",
        policySrc: "/src/policy",
        policyDest: "/dest/policy",
        installScript: "/scripts/install-polkit.sh",
        existsSync: (p) => p !== "/dest/policy",
        readFileSync: () => src,
        which: (b) => (b === "sudo" ? "/usr/bin/sudo" : null),
        runInstall: (c, a) => {
          calls.push(`${c} ${a.join(" ")}`);
        },
        log: (m) => logs.push(m),
      },
    );
    expect(calls).toEqual(["/usr/bin/sudo /scripts/install-polkit.sh"]);
    expect(logs.some((l) => l.startsWith("running:"))).toBe(true);
  });
});
